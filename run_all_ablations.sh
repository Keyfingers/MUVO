#!/bin/bash

################################################################################
# 🔬 一键运行所有消融实验
#
# 用法: bash run_all_ablations.sh
#
# 说明: 
#   - 自动运行5个消融实验（每个20 epochs）
#   - 所有实验串行执行，避免GPU冲突
#   - 自动保存日志
#   - 完成后自动生成对比报告
################################################################################

set -e  # 遇到错误立即退出

echo "================================================================================"
echo "🔬 开始消融实验批量运行"
echo "================================================================================"
echo ""
echo "📋 实验计划:"
echo "   1. Image-Only      (仅图像分支)"
echo "   2. LiDAR-Only      (仅点云分支)"
echo "   3. Late Fusion     (后期融合)"
echo "   4. Dynamic-Only    (仅异常数据训练)"
echo "   5. Lightweight     (轻量级模型)"
echo ""
echo "⏱️  预计总时间: 3-4小时 (每个实验约30-40分钟)"
echo ""
read -p "按Enter键开始，或Ctrl+C取消: "
echo ""

# 创建日志目录
mkdir -p ablation_results/logs

# 记录开始时间
START_TIME=$(date +%s)

################################################################################
# 实验1: Image-Only
################################################################################

echo "================================================================================"
echo "🔴 实验1/5: Image-Only (仅图像分支)"
echo "================================================================================"
echo ""

python ablation_study.py \
    --experiment image_only \
    --epochs 20 \
    --batch_size 8 \
    --lr 1e-4 \
    2>&1 | tee ablation_results/logs/image_only.log

echo ""
echo "✅ Image-Only 完成！"
echo ""

################################################################################
# 实验2: LiDAR-Only
################################################################################

echo "================================================================================"
echo "🟡 实验2/5: LiDAR-Only (仅点云分支)"
echo "================================================================================"
echo ""

python ablation_study.py \
    --experiment lidar_only \
    --epochs 20 \
    --batch_size 8 \
    --lr 1e-4 \
    2>&1 | tee ablation_results/logs/lidar_only.log

echo ""
echo "✅ LiDAR-Only 完成！"
echo ""

################################################################################
# 实验3: Late Fusion
################################################################################

echo "================================================================================"
echo "🟢 实验3/5: Late Fusion (后期融合)"
echo "================================================================================"
echo ""

python ablation_study.py \
    --experiment late_fusion \
    --epochs 20 \
    --batch_size 8 \
    --lr 1e-4 \
    2>&1 | tee ablation_results/logs/late_fusion.log

echo ""
echo "✅ Late Fusion 完成！"
echo ""

################################################################################
# 实验4: Dynamic-Only
################################################################################

echo "================================================================================"
echo "🔵 实验4/5: Dynamic-Only (仅异常数据训练)"
echo "================================================================================"
echo ""
echo "⚠️  警告: 此实验预期会失败（验证数据混合策略的重要性）"
echo ""

python ablation_study.py \
    --experiment dynamic_only \
    --epochs 20 \
    --batch_size 8 \
    --lr 1e-4 \
    2>&1 | tee ablation_results/logs/dynamic_only.log

echo ""
echo "✅ Dynamic-Only 完成（预期失败是正常的）"
echo ""

################################################################################
# 实验5: Lightweight
################################################################################

echo "================================================================================"
echo "🟣 实验5/5: Lightweight (轻量级模型)"
echo "================================================================================"
echo ""

python ablation_study.py \
    --experiment lightweight \
    --epochs 20 \
    --batch_size 8 \
    --lr 1e-4 \
    2>&1 | tee ablation_results/logs/lightweight.log

echo ""
echo "✅ Lightweight 完成！"
echo ""

################################################################################
# 生成对比报告
################################################################################

echo "================================================================================"
echo "📊 生成对比报告和图表"
echo "================================================================================"
echo ""

python compare_ablations.py 2>&1 | tee ablation_results/logs/comparison.log

################################################################################
# 总结
################################################################################

END_TIME=$(date +%s)
DURATION=$((END_TIME - START_TIME))
HOURS=$((DURATION / 3600))
MINUTES=$(((DURATION % 3600) / 60))

echo ""
echo "================================================================================"
echo "🎉 所有消融实验完成！"
echo "================================================================================"
echo ""
echo "⏱️  总耗时: ${HOURS}小时 ${MINUTES}分钟"
echo ""
echo "📂 结果位置:"
echo "   - 单个实验结果: ablation_results/[experiment_name]/"
echo "   - 对比分析:     ablation_results/comparison/"
echo "   - 训练日志:     ablation_results/logs/"
echo ""
echo "📊 生成的文件:"
echo "   ✓ 性能对比图表 (PNG + PDF)"
echo "   ✓ 混淆矩阵对比"
echo "   ✓ 训练曲线对比"
echo "   ✓ 参数-性能权衡图"
echo "   ✓ LaTeX表格 (可直接用于论文)"
echo "   ✓ 详细分析报告"
echo ""
echo "🚀 下一步:"
echo "   1. 查看 ablation_results/comparison/analysis_report.txt"
echo "   2. 使用生成的图表和表格撰写论文"
echo ""
echo "================================================================================"


